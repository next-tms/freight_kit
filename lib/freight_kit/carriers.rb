module FreightKit
  module Carriers
    module_function

    @registered = []

    def all = registered.map { |name| const_get(name) }

    def find(name)
      all.find { |c| c.name.downcase == name.to_s.downcase } or raise NameError, "unknown carrier #{name}"
    end

    def find_by(**attributes)
      all.find { |carrier| attributes.all? { |key, value| carrier.public_send(key) == value } }
    end

    def register(class_name) = registered << class_name
    def registered = @registered
  end
end

